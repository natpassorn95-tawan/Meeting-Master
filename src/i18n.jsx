const WEEKDAYS = {
  zh: ["日", "一", "二", "三", "四", "五", "六"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
};
const WEEKDAYS_FULL = {
  zh: ["週日", "週一", "週二", "週三", "週四", "週五", "週六"],
  en: ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"],
};
const ORDINALS = {
  zh: { 1: "第一個", 2: "第二個", 3: "第三個", 4: "第四個", 5: "最後一個" },
  en: { 1: "1st", 2: "2nd", 3: "3rd", 4: "4th", 5: "last" },
};

// Format a YYYY-MM-DD (+times) into a localized display string.
export function fmtDateTimeI18n(date, start, end, lang) {
  if (!date) return "";
  const [y, m, d] = date.split("-").map(Number);
  if (!y || !m || !d) return "";
  const wd = WEEKDAYS[lang][new Date(y, m - 1, d).getDay()];
  const dateStr = lang === "en"
    ? `${String(m).padStart(2, "0")}/${String(d).padStart(2, "0")}/${y} (${wd})`
    : `${y}/${String(m).padStart(2, "0")}/${String(d).padStart(2, "0")} (${wd})`;
  const time = start ? (end ? `${start}–${end}` : start) : "";
  return time ? `${dateStr} ${time}` : dateStr;
}

// Format a recurring schedule's rule, e.g. "每月第一個週五 14:00" / "Monthly 1st Fri 14:00".
export function recurrenceTextI18n(s, lang) {
  const wd = WEEKDAYS[lang][s.recurrence.weekday]; // short: "五" / "Fri"
  const time = s.startTime || "";
  if (s.recurrence.freq === "once") {
    const occ = fmtDateTimeI18n(s.recurrence.date, s.startTime, s.endTime, lang);
    return lang === "en" ? `One-time ${occ}` : `單次 ${occ}`;
  }
  if (s.recurrence.freq === "weekly") {
    return lang === "en" ? `Weekly ${wd} ${time}` : `每週${wd} ${time}`;
  }
  const ord = ORDINALS[lang][s.recurrence.nth || 1];
  return lang === "en" ? `Monthly ${ord} ${wd} ${time}` : `每月${ord}週${wd} ${time}`;
}

export function ordinalText(nth, lang) {
  return ORDINALS[lang]?.[nth] ?? ORDINALS.zh[nth] ?? String(nth);
}

const LangCtx = createContext({ lang: "zh", t: (k) => k, setLang: () => {}, weekdayFull: () => "" });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem("mm_lang") || "zh"; } catch { return "zh"; }
  });
  const setLang = (l) => {
    try { localStorage.setItem("mm_lang", l); } catch { /* ignore */ }
    setLangState(l);
  };
  const t = (key, params) => {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.zh[key] ?? key;
    if (params) for (const k of Object.keys(params)) s = s.split(`{${k}}`).join(params[k]);
    return s;
  };
  const weekdayFull = (idx) => WEEKDAYS_FULL[lang][idx];
  return <LangCtx.Provider value={{ lang, t, setLang, weekdayFull }}>{children}</LangCtx.Provider>;
}

export const useT = () => useContext(LangCtx);
